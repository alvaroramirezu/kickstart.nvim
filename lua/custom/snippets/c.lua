local ls = require 'luasnip'
local s = ls.snippet
local t = ls.text_node
local i = ls.insert_node
local f = ls.function_node

-- Helpers
local function filename()
  return vim.fn.expand '%:t'
end

local function header_guard()
  local base = vim.fn.expand '%:t:r'
  if base == nil or base == '' then
    base = 'HEADER'
  end
  base = base:gsub('[^%w]', '_')
  return base:upper() .. '_H'
end

return {
  -- C Header Template (chead)
  s('chead', {
    t '/******************************************************************************',
    t { '', ' * @file    ' },
    f(filename, {}),
    t { '', ' * @brief   ' },
    i(1, 'Brief description of this file.'), -- cursor starts here
    t { '', ' ******************************************************************************/', '' },

    t '#ifndef ',
    f(header_guard, {}),
    t { '', '#define ' },
    f(header_guard, {}),
    t { '', '' },

    t '#ifdef __cplusplus',
    t { '', 'extern "C" {', '#endif', '' },

    t '/******************************************************************************',
    t { '', ' * Includes', ' ******************************************************************************/', '', '' },

    t '/******************************************************************************',
    t { '', ' * Public Macros', ' ******************************************************************************/', '' },

    t '/******************************************************************************',
    t { '', ' * Public Types', ' ******************************************************************************/', '' },

    t '/******************************************************************************',
    t { '', ' * Public Functions Prototypes', ' ******************************************************************************/', '' },

    t '#ifdef __cplusplus',
    t { '', '}', '#endif', '' },

    t '#endif /* ',
    f(header_guard, {}),
    t ' */',
    i(0), -- final cursor stop
  }),

  -- C Source Template (csrc)
  s('csrc', {
    t '/******************************************************************************',
    t { '', ' * @file    ' },
    f(filename, {}),
    t { '', ' * @brief   ' },
    i(1, 'Brief description of this file.'), -- cursor starts here
    t { '', ' ******************************************************************************/', '' },

    t '/******************************************************************************',
    t { '', ' * Includes', ' ******************************************************************************/', '', '' },

    t '/******************************************************************************',
    t { '', ' * Private Macros', ' ******************************************************************************/', '' },

    t '/******************************************************************************',
    t { '', ' * Private Types', ' ******************************************************************************/', '' },

    t '/******************************************************************************',
    t { '', ' * Private Global Variables', ' ******************************************************************************/', '' },

    t '/******************************************************************************',
    t { '', ' * Private Function Prototypes', ' ******************************************************************************/', '' },

    t '/******************************************************************************',
    t { '', ' * Private Functions', ' ******************************************************************************/', '', '' },

    t '/******************************************************************************',
    t { '', ' * Public Functions', ' ******************************************************************************/', '', '' },

    t '/****End of File****/',
    i(0),
  }),

  -- Title section comment (ctitle)
  s('ctitle', {
    t '/******************************************************************************',
    t { '', ' * ' },
    i(1, 'Section Title'),
    t { '', ' ******************************************************************************/' },
  }),
}
